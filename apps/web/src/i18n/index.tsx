export type Lang = keyof typeof dict;
export type MsgKey = keyof (typeof dict)["sl"];

const LS_KEY = "ikataster.lang";
const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: MsgKey) => string } | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => (localStorage.getItem(LS_KEY) as Lang) || "sl");
  const setLang = (l: Lang) => {
    localStorage.setItem(LS_KEY, l);
    document.documentElement.lang = l;
    setLangState(l);
  };
  return <Ctx.Provider value={{ lang, setLang, t: (k) => dict[lang][k] }}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const c = useContext(Ctx);
  if (!c) throw new Error("useI18n outside I18nProvider");
  return c;
}
